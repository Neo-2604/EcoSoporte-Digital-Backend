"""
EcoSoporte Digital · Pantalla de integraciones (Google Cloud / Vertex AI). Solo Administrador.

  * Estado de la configuración (nombres de variables, nunca valores) y prueba de conexión.
  * Autorización explícita para enviar textos de tickets a Vertex AI (apagada por defecto, con registro de quién y cuándo).
  * Contador de uso diario (sin guardar el contenido de las llamadas).
Las llamadas a Google las hace únicamente gcloud_service.py.
"""
from datetime import datetime
from functools import wraps
from flask import Blueprint, flash, g, redirect, render_template, request, url_for

import gcloud_service as gs

bp = Blueprint("integrations", __name__, url_prefix="/integraciones")
_db = _roles = None


def guard(*roles):
    def deco(fn):
        @wraps(fn)
        def w(*a, **k): return _roles(*roles)(fn)(*a, **k)
        return w
    return deco


def _now(): return datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")


def ensure_schema(c):
    pk = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    c.execute("CREATE TABLE IF NOT EXISTS ml_settings(key TEXT PRIMARY KEY, value TEXT, updated_by INTEGER, updated_name TEXT, updated_at TEXT)")
    c.execute(f"CREATE TABLE IF NOT EXISTS ml_usage(id {pk}, day TEXT NOT NULL, kind TEXT NOT NULL, ok BOOLEAN NOT NULL, status TEXT, created_at TEXT NOT NULL)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_ml_usage_day ON ml_usage(day)")


class DbUsage:
    """Almacén de uso en PostgreSQL: solo cuenta llamadas; no guarda textos enviados ni respuestas."""
    def count_today(self):
        return _db().execute("SELECT COUNT(*) n FROM ml_usage WHERE day=%s", (datetime.utcnow().strftime("%Y-%m-%d"),)).fetchone()["n"]

    def record(self, kind, ok, status_text):
        c = _db(); c.execute("INSERT INTO ml_usage(day,kind,ok,status,created_at) VALUES(%s,%s,%s,%s,%s)",
                             (datetime.utcnow().strftime("%Y-%m-%d"), kind, bool(ok), (status_text or "")[:30], _now())); c.commit()


def consent(c, key="tickets_consent"):
    r = c.execute("SELECT * FROM ml_settings WHERE key=%s", (key,)).fetchone()
    return r if r and r["value"] == "1" else None


def vertex_allowed(c):
    """(permitido, motivo): integración lista Y autorización del administrador para textos de tickets."""
    if not gs.is_ready(): return False, "La integración con Google Cloud no está activada o configurada."
    if not consent(c): return False, "Un administrador debe autorizar el envío de textos de tickets a Vertex AI (Integraciones › Google Cloud)."
    return True, ""


@bp.route("/google")
@guard("Administrador")
def google():
    c = _db()
    return render_template("integrations_google.html", st=gs.status(), consent=consent(c), used=gs.usage_today(),
                           results=None)


@bp.post("/google/autorizacion")
@guard("Administrador")
def google_consent():
    c = _db(); on = request.form.get("accion") == "autorizar"
    if on and request.form.get("entiendo") != "1":
        flash("Marca la casilla para confirmar que entiendes qué se envía.", "error"); return redirect(url_for("integrations.google"))
    c.execute("""INSERT INTO ml_settings(key,value,updated_by,updated_name,updated_at) VALUES('tickets_consent',%s,%s,%s,%s)
                 ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value, updated_by=EXCLUDED.updated_by, updated_name=EXCLUDED.updated_name, updated_at=EXCLUDED.updated_at""",
              ("1" if on else "0", g.user["id"], g.user["name"], _now()))
    try:
        import payroll; payroll.audit(c, "ml_autorizacion_" + ("activada" if on else "retirada"), "textos de tickets → Vertex AI")
    except Exception: pass
    c.commit(); flash("Autorización registrada." if on else "Autorización retirada: no se enviará ningún texto a Google.", "success")
    return redirect(url_for("integrations.google"))


@bp.post("/google/probar")
@guard("Administrador")
def google_test():
    c = _db(); real = request.form.get("modo") == "real"
    if real and request.form.get("confirmo") != "1":
        flash("Para la llamada real confirma que consume una llamada de cuota (puede tener un costo mínimo).", "error"); return redirect(url_for("integrations.google"))
    results = gs.check_connection(call_model=real)
    try:
        import payroll; payroll.audit(c, "ml_prueba_conexion", "real" if real else "sin costo"); c.commit()
    except Exception: pass
    return render_template("integrations_google.html", st=gs.status(), consent=consent(c), used=gs.usage_today(), results=results, real=real)


def setup(app, db, roles_required):
    global _db, _roles
    _db, _roles = db, roles_required
    gs.set_usage_store(DbUsage())
    app.register_blueprint(bp)
