    if not r: abort(404)
    if r["status"] != PARAM_PENDING: flash("Ese registro ya fue resuelto.", "error")
    elif not _two_person_ok(r["proposed_by"]): flash("Debe aprobarlo un administrador distinto al que lo propuso.", "error")
