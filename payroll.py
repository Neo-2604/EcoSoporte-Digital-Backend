# ------------------------------------------------------------------ infraestructura
def guard(*roles):
    def deco(fn):
        @wraps(fn)
        def wrapper(*a, **k):
            return _roles(*roles)(fn)(*a, **k)
        return wrapper
    return deco


def _now():
    return datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")


def _num(v, kind, lo, hi):
    """Convierte y valida un número de formulario. Devuelve (valor | None)."""
    try:
        x = float(str(v).strip().replace(",", "."))
    except (TypeError, ValueError):
        return None
    if x != x or x in (float("inf"), float("-inf")) or x < lo or x > hi:
        return None
    if kind == "int":
        return int(round(x))
    if kind == "pct":
        return round(x / 100.0, 4)
    return round(x, 2)


