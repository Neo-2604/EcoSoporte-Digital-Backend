def _safe(v):
    """Evita inyección de fórmulas al abrir en Excel."""
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + v
    return v


@bp.route("/exportar.<fmt>")
@guard("Administrador")
def export(fmt):
    if fmt not in ("csv", "xlsx"): abort(404)
    c = _db(); period, tech, status = _filters()
    rows = _settlement_rows(c, period, tech, status, "Administrador", g.user["id"])
    head = ["Periodo", "Trabajador", "ID", "Salario base", "Auxilio de transporte", "Tickets validados", "Puntos", "Calidad %", "ANS %",
            "Satisfacción", "Puntos bonificados", "Bono", "Total", "Estado", "Aprobado por", "Fecha aprobación (UTC)", "Pagado por",
            "Fecha de pago (UTC)", "Referencia de pago"]
    def line(r):
        return [r["period"], r["user_name"], r["user_code"] or "", r["base_salary"], r["transport_aid"], r["tickets_count"], r["points"],
                None if r["quality"] is None else round(r["quality"] * 100, 1), None if r["ans"] is None else round(r["ans"] * 100, 1),
                None if r["satisfaction"] is None else round(r["satisfaction"], 2), r["bonus_points"], r["bonus_amount"], r["total"], r["status"],
                r["approved_name"] or "", r["approved_at"] or "", r["paid_name"] or "", r["paid_at"] or "", r["payment_ref"] or ""]
    audit(c, "exportacion", f"{fmt} · {len(rows)} filas"); c.commit()
    name = f"nomina_{period or 'todos'}.{fmt}"
    if fmt == "csv":
        buf = io.StringIO(); w = csv.writer(buf); w.writerow(head)
        for r in rows: w.writerow([_safe(x) if x is not None else "" for x in line(r)])
        return Response("﻿" + buf.getvalue(), mimetype="text/csv; charset=utf-8", headers={"Content-Disposition": f"attachment; filename={name}"})
    from openpyxl import Workbook
    wb = Workbook(); ws = wb.active; ws.title = "Liquidaciones"; ws.append(head)
    for r in rows: ws.append([_safe(x) for x in line(r)])
    for col in "ABCDEFGHIJKLMNOPQRS": ws.column_dimensions[col].width = 18
    out = io.BytesIO(); wb.save(out)
    return Response(out.getvalue(), mimetype="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": f"attachment; filename={name}"})


