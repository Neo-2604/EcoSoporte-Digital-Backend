def rate_ticket(tid):
    c = _db()
    from app import login_required  # importación tardía: evita dependencia circular al cargar
    @login_required
    def inner():
        t = c.execute("SELECT id,created_by,status,satisfaction FROM tickets WHERE id=%s", (tid,)).fetchone()
        if not t: abort(404)
        if t["created_by"] != g.user["id"]: abort(403)
        try: score = int(request.form.get("score", ""))
        except ValueError: score = 0
        if t["status"] not in ("Resuelto", "Cerrado"): flash("Podrás calificar cuando el ticket esté resuelto.", "error")
        elif t["satisfaction"]: flash("Este ticket ya fue calificado.", "error")
        elif not 1 <= score <= 5: flash("Elige una calificación de 1 a 5.", "error")
        else:
            c.execute("UPDATE tickets SET satisfaction=%s WHERE id=%s", (score, tid)); c.commit()
            flash("¡Gracias por calificar la atención!", "success")
        return redirect(url_for("ticket_detail", ticket_id=tid))
    return inner()


