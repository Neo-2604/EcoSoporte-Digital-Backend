@bp.post("/configuracion/<kind>/<int:rid>/<action>")
@guard("Administrador")
def config_action(kind, rid, action):
    c = _db()
    table = {"params": "payroll_params", "salary": "payroll_salaries"}.get(kind)
    if not table or action not in ("aprobar", "rechazar"): abort(404)
