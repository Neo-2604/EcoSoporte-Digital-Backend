        new = PARAM_APPROVED if action == "aprobar" else PARAM_REJECTED
        c.execute(f"UPDATE {table} SET status=%s,approved_by=%s,approved_name=%s,approved_at=%s WHERE id=%s", (new, g.user["id"], g.user["name"], _now(), rid))
