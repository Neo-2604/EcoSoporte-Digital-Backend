def _two_person_ok(proposer_id):
    """El aprobador debe ser otra persona que quien propuso (salvo que se desactive explícitamente)."""
    if os.environ.get("PAYROLL_ALLOW_SELF_APPROVAL") == "1":
        return True
    return proposer_id is None or proposer_id != g.user["id"]


# ------------------------------------------------------------------ periodos y datos vigentes
def valid_period(p):
    return bool(p) and re.fullmatch(r"20\d\d-(0[1-9]|1[0-2])", p) is not None


def bounds(period):
    y, m = int(period[:4]), int(period[5:7])
    start = datetime(y, m, 1)
    end = datetime(y + (m == 12), 1 if m == 12 else m + 1, 1)
    f = "%Y-%m-%d %H:%M:%S"
    return start.strftime(f), end.strftime(f)


def current_period():
    return datetime.utcnow().strftime("%Y-%m")


def active_params(c):
    return c.execute("SELECT * FROM payroll_params WHERE status=%s ORDER BY approved_at DESC, id DESC LIMIT 1", (PARAM_APPROVED,)).fetchone()


def salary_for(c, uid, period):
    end_day = bounds(period)[1][:10]
    return c.execute("""SELECT * FROM payroll_salaries WHERE user_id=%s AND status=%s AND effective_from<%s
                        ORDER BY effective_from DESC, id DESC LIMIT 1""", (uid, PARAM_APPROVED, end_day)).fetchone()


# ------------------------------------------------------------------ cálculo (determinista y transparente)
def performance(c, uid, period, params):
    """Métricas reales del técnico en el periodo. params puede ser None (se usan los valores de referencia sin bono)."""
    p = params or DEFAULT_PARAMS
    start, end = bounds(period)
    rows = c.execute("""
        SELECT t.id, t.title, t.priority, t.complexity, t.bonus_excluded, t.resolved_at, t.solution_due, t.satisfaction,
               EXISTS(SELECT 1 FROM ticket_updates u WHERE u.ticket_id=t.id AND u.created_at>t.resolved_at
                      AND u.status IN ('Abierto','En proceso','En espera')) AS reopened
        FROM tickets t WHERE t.assigned_to=%s AND t.status IN ('Resuelto','Cerrado')
              AND t.resolved_at>=%s AND t.resolved_at<%s ORDER BY t.resolved_at""", (uid, start, end)).fetchall()
    pts = {"Básico": p["pts_basic"], "Medio": p["pts_medium"], "Complejo": p["pts_complex"]}
    tickets, valid = [], []
    for r in rows:
        level = r["complexity"] if r["complexity"] in pts else "Básico"
        excluded = bool(r["bonus_excluded"])
        value = 0 if excluded else pts[level]
        on_time = None if not r["solution_due"] else (r["resolved_at"] <= r["solution_due"])
        tickets.append(dict(id=r["id"], title=r["title"], priority=r["priority"], complexity=level, excluded=excluded, points=value,
                            resolved_at=r["resolved_at"], on_time=on_time, reopened=bool(r["reopened"]), satisfaction=r["satisfaction"],
                            code=f"TCK-{r['resolved_at'][:4]}-{r['id']:04d}"))
        if not excluded:
            valid.append(tickets[-1])
    n = len(valid)
    points = round(sum(t["points"] for t in valid), 2)
    quality = (1 - sum(1 for t in valid if t["reopened"]) / n) if n else None
    due = [t for t in valid if t["on_time"] is not None]
    ans = (sum(1 for t in due if t["on_time"]) / len(due)) if due else None
    ratings = [t["satisfaction"] for t in valid if t["satisfaction"]]
    sat = (sum(ratings) / len(ratings)) if len(ratings) >= p["min_ratings"] and ratings else None
    return dict(tickets=tickets, count=n, excluded=len(tickets) - n, points=points, quality=quality, ans=ans,
                satisfaction=sat, ratings=len(ratings))


def _pct(x):
    return "sin datos" if x is None else f"{x * 100:.1f}%"


def bonus(perf, p):
    """Aplica la política. Devuelve dict con puntos bonificados, monto y las líneas explicadas."""
    goal, cap, rate = p["goal_points"], p["max_bonus_points"], p["bonus_per_point"]
    conds = [
        ("Calidad (cierres sin reapertura)", _pct(perf["quality"]), f"≥ {p['min_quality'] * 100:.1f}%",
         perf["quality"] is not None and perf["quality"] >= p["min_quality"]),
        ("Cumplimiento de ANS", _pct(perf["ans"]), f"≥ {p['min_ans'] * 100:.1f}%",
         perf["ans"] is not None and perf["ans"] >= p["min_ans"]),
    ]
    if perf["satisfaction"] is None:
        conds.append(("Satisfacción del cliente", f"sin datos suficientes ({perf['ratings']} de {p['min_ratings']} calificaciones)",
                      "no se penaliza", True))
    else:
        conds.append(("Satisfacción del cliente", f"{perf['satisfaction']:.2f} / 5", f"≥ {p['min_satisfaction']:.1f}",
                      perf["satisfaction"] >= p["min_satisfaction"]))
    extra = max(0.0, perf["points"] - goal)
    eligible = all(ok for *_, ok in conds)
    paid_pts = min(extra, cap) if eligible else 0.0
    amount = int(round(paid_pts * rate))
    lines = [
        ("Puntos validados del periodo", f"{perf['points']:g}", f"{perf['count']} tickets resueltos (se excluyen {perf['excluded']})"),
        ("Meta mensual", f"{goal:g}", "puntos"),
        ("Puntos sobre la meta", f"{extra:g}", "máx(0, validados − meta)"),
        ("Tope de puntos bonificados", f"{cap:g}", "límite mensual"),
        ("¿Cumple las condiciones?", "Sí" if eligible else "No", "calidad, ANS y satisfacción (si hay datos)"),
        ("Puntos bonificados", f"{paid_pts:g}", "mín(puntos sobre la meta, tope) si cumple; si no, 0"),
        ("Valor por punto", f"${rate:,.0f}".replace(",", "."), "COP"),
        ("Bono bruto", f"${amount:,.0f}".replace(",", "."), "puntos bonificados × valor por punto"),
    ]
    return dict(eligible=eligible, bonus_points=paid_pts, amount=amount, conditions=conds, lines=lines)


def build_settlement(c, uid, period, replace_pending=True):
    """Crea o recalcula la liquidación de un trabajador. Devuelve (id | None, mensaje de error | None)."""
    params = active_params(c)
    if not params:
        return None, "No hay parámetros aprobados. Apruébalos en Configuración antes de liquidar."
    user = c.execute("SELECT id,name,role,tech_code FROM users WHERE id=%s", (uid,)).fetchone()
    if not user or user["role"] not in SALARIED_ROLES:
        return None, "Trabajador no válido."
    sal = salary_for(c, uid, period)
    if not sal:
        return None, f"{user['name']} no tiene un salario aprobado vigente para {period}."
    existing = c.execute("SELECT id,status FROM payroll_settlements WHERE user_id=%s AND period=%s", (uid, period)).fetchone()
    if existing and existing["status"] != PENDING:
        return None, f"La liquidación de {user['name']} para {period} ya está {existing['status'].lower()} y no se puede recalcular."
    perf = performance(c, uid, period, params)
    is_tech = user["role"] == "Técnico"
    b = bonus(perf, params) if is_tech else dict(eligible=False, bonus_points=0.0, amount=0, conditions=[], lines=[])
    transport = params["transport_aid"] if sal["transport_aid"] and sal["base_salary"] <= 2 * params["smmlv"] else 0
    total = sal["base_salary"] + transport + b["amount"]
    snap = json.dumps(dict(params={k: params[k] for k in DEFAULT_PARAMS}, perf=perf, bonus=b, is_tech=is_tech), ensure_ascii=False, default=str)
    vals = (user["name"], user["tech_code"], sal["base_salary"], transport, perf["count"], perf["points"], perf["quality"],
            perf["ans"], perf["satisfaction"], b["bonus_points"], b["amount"], total, params["id"], sal["id"], snap, _now())
    if existing:
        c.execute("""UPDATE payroll_settlements SET user_name=%s,user_code=%s,base_salary=%s,transport_aid=%s,tickets_count=%s,points=%s,
                     quality=%s,ans=%s,satisfaction=%s,bonus_points=%s,bonus_amount=%s,total=%s,params_id=%s,salary_id=%s,breakdown=%s,
                     updated_at=%s WHERE id=%s""", vals + (existing["id"],))
        sid = existing["id"]
    else:
        sid = c.execute("""INSERT INTO payroll_settlements(user_id,period,user_name,user_code,base_salary,transport_aid,tickets_count,points,
                           quality,ans,satisfaction,bonus_points,bonus_amount,total,params_id,salary_id,breakdown,created_by,created_name,
                           created_at,updated_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
                        (uid, period) + vals[:-1] + (g.user["id"], g.user["name"], vals[-1], vals[-1])).fetchone()["id"]
    return sid, None


# ------------------------------------------------------------------ pantallas
def _money(v):
    return "—" if v is None else "$" + f"{int(v):,}".replace(",", ".")


def _filters():
    period = request.args.get("periodo", "").strip()
    if period and not valid_period(period):
        period = ""
    tech = request.args.get("tecnico", "").strip()
    tech = int(tech) if tech.isdigit() else None
    status = request.args.get("estado", "").strip()
    return period, tech, (status if status in SETTLEMENT_STATUSES else "")


def _settlement_rows(c, period, tech, status, role, uid):
    where, args = ["1=1"], []
    if role == "Técnico":
        where += ["user_id=%s", "status IN (%s,%s)"]; args += [uid, APPROVED, PAID]
    if period: where.append("period=%s"); args.append(period)
    if tech and role != "Técnico": where.append("user_id=%s"); args.append(tech)
    if status: where.append("status=%s"); args.append(status)
    return c.execute(f"SELECT * FROM payroll_settlements WHERE {' AND '.join(where)} ORDER BY period DESC, user_name", args).fetchall()


def _team_performance(c, period, tech, role, uid):
    params = active_params(c)
    people = c.execute("SELECT id,name,tech_code,role FROM users WHERE active AND role='Técnico' ORDER BY name").fetchall()
    out = []
    for u in people:
        if role == "Técnico" and u["id"] != uid: continue
        if tech and u["id"] != tech: continue
        perf = performance(c, u["id"], period, params)
        b = bonus(perf, params) if params else None
        out.append(dict(user=u, perf=perf, bonus=b))
    return out, params


@bp.route("/")
@guard("Administrador", "Soporte TI", "Técnico")
def index():
    c, role = _db(), g.user["role"]
    period, tech, status = _filters()
    perf_period = period or current_period()
    # Soporte TI ve desempeño pero NO montos: no se consultan liquidaciones para ese rol
    rows = _settlement_rows(c, period, tech, status, role, g.user["id"]) if role in ("Administrador", "Técnico") else []
    team, params = _team_performance(c, perf_period, tech, role, g.user["id"])
    is_admin = role == "Administrador"
    stats = dict(pending=sum(1 for r in rows if r["status"] == PENDING), approved=sum(1 for r in rows if r["status"] == APPROVED),
                 paid=sum(1 for r in rows if r["status"] == PAID), total=sum(r["total"] for r in rows if r["status"] in (APPROVED, PAID)))
    technicians = c.execute("SELECT id,name,tech_code FROM users WHERE active AND role='Técnico' ORDER BY name").fetchall()
    workers = c.execute("SELECT id,name,tech_code,role FROM users WHERE active AND role IN ('Técnico','Soporte TI','Administrador') ORDER BY name").fetchall()
    periods = [r["period"] for r in c.execute("SELECT DISTINCT period FROM payroll_settlements ORDER BY period DESC LIMIT 24").fetchall()]
    return render_template("payroll.html", rows=rows, team=team, params=params, period=period, perf_period=perf_period, tech=tech,
                           status=status, stats=stats, technicians=technicians, workers=workers, periods=periods, is_admin=is_admin,
                           money=_money, statuses=SETTLEMENT_STATUSES, pct=_pct, legal_note=LEGAL_NOTE, default_period=current_period())


@bp.post("/generar")
@guard("Administrador")
def generate():
    c = _db()
    period = request.form.get("periodo", "")
    if not valid_period(period):
        flash("Periodo no válido (usa AAAA-MM).", "error"); return redirect(url_for("payroll.index"))
    uid = request.form.get("user_id", "")
    ids = [int(uid)] if uid.isdigit() else [r["id"] for r in c.execute("SELECT id FROM users WHERE active AND role IN ('Técnico','Soporte TI','Administrador')").fetchall()]
    made, errors = 0, []
    for i in ids:
        sid, err = build_settlement(c, i, period)
        if sid: made += 1; audit(c, "liquidacion_generada", f"{period} · trabajador {i}")
        elif uid.isdigit() or "ya está" not in (err or "") and "salario aprobado" not in (err or ""): errors.append(err)
    c.commit()
    if made: flash(f"Se generaron o actualizaron {made} liquidaciones de {period} (pendientes de revisión).", "success")
    elif not errors: flash("No hay trabajadores con salario aprobado para ese periodo.", "error")
    for e in errors[:3]: flash(e, "error")
    return redirect(url_for("payroll.index", periodo=period))


def _load(sid):
    c = _db()
    s = c.execute("SELECT * FROM payroll_settlements WHERE id=%s", (sid,)).fetchone()
    if not s: abort(404)
    role = g.user["role"]
    if role == "Administrador": pass
    elif role == "Técnico" and s["user_id"] == g.user["id"] and s["status"] in (APPROVED, PAID): pass
    else: abort(403)
    return s


