def activity_data():
    c = _db(); t_online = _ago(ONLINE_SECONDS)
    online = c.execute("SELECT p.kind, p.path, p.last_seen, p.first_seen, u.name, u.role FROM presence p LEFT JOIN users u ON u.id=p.user_id "
                       "WHERE p.last_seen>=? ORDER BY p.last_seen DESC", (t_online,)).fetchall()
    online = [dict(r) for r in online]
    today = now()[:10]
    since = (datetime.utcnow() - timedelta(days=6)).strftime("%Y-%m-%d")
    views = [dict(r) for r in c.execute("SELECT session_key, kind, user_id, path, created_at FROM page_views WHERE created_at>=?", (since + " 00:00:00",)).fetchall()]
    by_day = {}
    for i in range(7):
        by_day[(datetime.utcnow() - timedelta(days=6 - i)).strftime("%Y-%m-%d")] = {"views": 0, "visitors": set()}
    pages = {}
    for v in views:
        day = v["created_at"][:10]
        if day in by_day:
            by_day[day]["views"] += 1; by_day[day]["visitors"].add(v["session_key"])
        pages[v["path"]] = pages.get(v["path"], 0) + 1
    days = [{"day": d, "views": x["views"], "visitors": len(x["visitors"])} for d, x in by_day.items()]
    top = sorted(({"path": p, "n": n} for p, n in pages.items()), key=lambda r: -r["n"])[:8]
    last_users = [dict(r) for r in c.execute(
        "SELECT u.name, u.email, u.role, MAX(p.last_seen) last_seen, COUNT(p.id) sessions FROM presence p JOIN users u ON u.id=p.user_id "
        "GROUP BY u.id, u.name, u.email, u.role ORDER BY last_seen DESC LIMIT 15").fetchall()]
    today_views = by_day.get(today, {"views": 0, "visitors": set()})
    return {
        "online_total": len(online),
        "online_app": sum(1 for o in online if o["kind"] == "app"),
        "online_web": sum(1 for o in online if o["kind"] == "web"),
        "online_users": [o for o in online if o["name"]],
        "online_anonymous": sum(1 for o in online if not o["name"]),
        "today_views": today_views["views"], "today_visitors": len(today_views["visitors"]),
        "days": days, "top_pages": top, "last_users": last_users, "now": now(),
    }


