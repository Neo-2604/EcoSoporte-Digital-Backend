def ensure_schema(c):
    pk = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    stmts = f"""
    CREATE TABLE IF NOT EXISTS presence(
      id {pk}, session_key TEXT UNIQUE NOT NULL, kind TEXT NOT NULL DEFAULT 'web', user_id INTEGER,
      path TEXT, user_agent TEXT, first_seen TEXT NOT NULL, last_seen TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS page_views(
      id {pk}, session_key TEXT NOT NULL, kind TEXT NOT NULL DEFAULT 'web', user_id INTEGER, path TEXT, created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS chat_sessions(
      id {pk}, token TEXT UNIQUE NOT NULL, state TEXT NOT NULL DEFAULT 'menu', data TEXT NOT NULL DEFAULT '{{}}',
      messages INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS chat_messages(
      id {pk}, session_id INTEGER NOT NULL, sender TEXT NOT NULL, text TEXT NOT NULL, created_at TEXT NOT NULL,
      FOREIGN KEY(session_id) REFERENCES chat_sessions(id));
    CREATE TABLE IF NOT EXISTS leads(
      id {pk}, kind TEXT NOT NULL, name TEXT, phone TEXT, email TEXT, company TEXT, city TEXT,
      subject TEXT, details TEXT, quantity TEXT, condition TEXT, preferred_time TEXT, consent INTEGER NOT NULL DEFAULT 0,
      status TEXT NOT NULL DEFAULT 'Nuevo', assigned_to INTEGER, appointment_at TEXT, notes TEXT,
      session_id INTEGER, created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
      FOREIGN KEY(assigned_to) REFERENCES users(id));
    CREATE TABLE IF NOT EXISTS remote_hosts(
      id {pk}, name TEXT NOT NULL, company_id INTEGER, address TEXT NOT NULL, port INTEGER NOT NULL DEFAULT 22,
      ssh_user TEXT NOT NULL, os TEXT, fingerprint TEXT, notes TEXT, active BOOLEAN NOT NULL DEFAULT TRUE,
      created_by INTEGER, created_at TEXT NOT NULL,
      FOREIGN KEY(company_id) REFERENCES companies(id), FOREIGN KEY(created_by) REFERENCES users(id));
    CREATE TABLE IF NOT EXISTS remote_sessions(
      id {pk}, host_id INTEGER NOT NULL, ticket_id INTEGER, technician_id INTEGER NOT NULL, reason TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'Solicitada', approved_by INTEGER, approved_at TEXT, started_at TEXT, ended_at TEXT,
      outcome TEXT, summary TEXT, created_at TEXT NOT NULL,
      FOREIGN KEY(host_id) REFERENCES remote_hosts(id), FOREIGN KEY(ticket_id) REFERENCES tickets(id),
      FOREIGN KEY(technician_id) REFERENCES users(id), FOREIGN KEY(approved_by) REFERENCES users(id));
    CREATE TABLE IF NOT EXISTS remote_events(
      id {pk}, session_id INTEGER NOT NULL, user_id INTEGER, action TEXT NOT NULL, detail TEXT, created_at TEXT NOT NULL,
      FOREIGN KEY(session_id) REFERENCES remote_sessions(id), FOREIGN KEY(user_id) REFERENCES users(id));
    """
    for stmt in stmts.split(";"):
        if stmt.strip():
            c.execute(stmt)
    c.execute("CREATE INDEX IF NOT EXISTS idx_presence_last_seen ON presence(last_seen)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_page_views_created ON page_views(created_at)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_remote_sessions_tech ON remote_sessions(technician_id)")


