def _create_host(d):
    c = _db()
    name, addr, user = _clip(d.get("name"), 80), _clip(d.get("address"), 120), _clip(d.get("ssh_user"), 40)
    if not (name and addr and user): return "Nombre, dirección y usuario SSH son obligatorios"
    if not re.fullmatch(r"[A-Za-z0-9._-]+", addr): return "La dirección solo puede tener letras, números, puntos y guiones"
    if not re.fullmatch(r"[a-z_][a-z0-9_-]*", user): return "Usuario SSH no válido (minúsculas, sin espacios)"
    port = _int(d.get("port"), 22)
    if not 1 <= port <= 65535: return "Puerto no válido"
    company = d.get("company_id") or None
    if company and not c.execute("SELECT id FROM companies WHERE id=?", (company,)).fetchone(): return "Empresa no válida"
    c.execute("INSERT INTO remote_hosts(name,company_id,address,port,ssh_user,os,fingerprint,notes,created_by,created_at) VALUES(?,?,?,?,?,?,?,?,?,?)",
              (name, company, addr, port, user, _clip(d.get("os"), 40) or None, _clip(d.get("fingerprint"), 120) or None, _clip(d.get("notes"), 300) or None, g.user["id"], now()))
    c.commit()
    return None


