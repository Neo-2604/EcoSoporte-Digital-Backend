def _apply_lead_update(lid, d):
    c = _db()
    if not c.execute("SELECT id FROM leads WHERE id=?", (lid,)).fetchone():
        return "Solicitud no encontrada"
    status = d.get("status")
    if status not in LEAD_STATUSES:
        return "Estado no válido"
    appt = _clip(d.get("appointment_at"), 25).replace("T", " ") or None
    if appt and not re.fullmatch(r"\d{4}-\d{2}-\d{2}( \d{2}:\d{2}(:\d{2})?)?", appt):
        return "La fecha de la cita no es válida"
    assignee = d.get("assigned_to") or None
    if assignee and not c.execute("SELECT id FROM users WHERE id=? AND active AND role IN ('Administrador','Soporte TI','Técnico')", (assignee,)).fetchone():
        return "Responsable no válido"
    if status == "Cita agendada" and not appt:
        return "Indica la fecha y hora de la cita"
    c.execute("UPDATE leads SET status=?, appointment_at=?, assigned_to=?, notes=?, updated_at=? WHERE id=?",
              (status, appt, assignee, _clip(d.get("notes"), 1000), now(), lid))
    c.commit()
    return None


