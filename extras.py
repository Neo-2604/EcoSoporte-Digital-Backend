def _current_user_soft():
    """Usuario si hay sesión web o token válido; None si es visitante anónimo."""
    h = request.headers.get("Authorization", "")
    if h.startswith("Bearer "):
        probe = _api_auth(lambda: None)
        if probe() is None:
            return g.user
        return None
    if session.get("user_id"):
        u = _db().execute("SELECT * FROM users WHERE id=? AND active", (session["user_id"],)).fetchone()
        return u
    return None


def api_roles(*roles):
    """Endpoint JSON para la app (token) o la web (sesión), limitado a ciertos roles."""
    def deco(fn):
        @wraps(fn)
        def w(*a, **k):
            u = _current_user_soft()
            if not u:
                return jsonify(error="No autenticado"), 401
            g.user = u
            if roles and u["role"] not in roles:
                return jsonify(error="No tienes permiso para esta acción"), 403
            return fn(*a, **k)
        return w
    return deco


def page_roles(*roles):
    """Página web protegida por rol (usa roles_required de app.py, resuelto al momento de la petición)."""
    def deco(fn):
        @wraps(fn)
        def w(*a, **k):
            return _roles_required(*roles)(fn)(*a, **k)
        return w
    return deco


def _clip(s, n):
    return (s or "").strip()[:n]


