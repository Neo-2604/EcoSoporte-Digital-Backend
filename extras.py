@bp.post("/api/chat/message")
def chat_message():
    d = request.get_json(silent=True) or {}
    c = _db()
    sess = c.execute("SELECT * FROM chat_sessions WHERE token=?", (str(d.get("token") or "")[:80],)).fetchone()
    if not sess:
        return jsonify(error="Sesión de chat no válida"), 404
    if sess["messages"] >= 120:
        return jsonify(replies=["Llegaste al límite de mensajes de esta conversación. Recarga la página para iniciar otra."], options=[], done=True)
    text = _clip(d.get("text"), 400)
    if not text:
        return jsonify(error="Mensaje vacío"), 400
    _log(c, sess["id"], "user", text)
    state, data, r = _chat_reply(sess, text)
    done = False
    if r.get("save"):
        lead_id = _save_lead(c, sess["id"], data)
        code = f"SOL-{datetime.utcnow().year}-{lead_id:04d}"
        r = {"replies": [f"¡Listo! Registré tu solicitud con el código {code}. Un asesor te contactará pronto.", "¿Necesitas algo más?"], "options": MAIN}
        state, data, done = "menu", {}, True
    for line in r["replies"]:
        _log(c, sess["id"], "bot", line)
    c.execute("UPDATE chat_sessions SET state=?, data=?, messages=messages+1, updated_at=? WHERE id=?",
              (state, json.dumps(data, ensure_ascii=False), now(), sess["id"]))
    c.commit()
    return jsonify(replies=r["replies"], options=r.get("options", []), done=done)


