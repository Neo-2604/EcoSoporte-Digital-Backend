def _cotime(ts):
    """UTC guardado -> hora de Colombia (UTC-5) para mostrar."""
    if not ts: return "—"
    try:
        return (datetime.strptime(ts[:19].replace("T", " "), "%Y-%m-%d %H:%M:%S") - timedelta(hours=5)).strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return ts


