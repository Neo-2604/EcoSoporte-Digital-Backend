class _Res:
    def __init__(self, cur, lastrowid=None): self._cur, self.lastrowid = cur, lastrowid
    def fetchone(self): return self._cur.fetchone() if self._cur.description else None
    def fetchall(self): return self._cur.fetchall() if self._cur.description else []
    def __iter__(self): return iter(self.fetchall())


class _Q:
    """Adaptador sobre la conexión de app.py: acepta "?" y entrega lastrowid en los INSERT."""
    def __init__(self, conn): self.c = conn
    def execute(self, sql, params=()):
        s = sql.replace("%", "%%").replace("?", "%s")
        ret = s.lstrip().upper().startswith("INSERT") and "RETURNING" not in s.upper()
        if ret: s = s.rstrip().rstrip(";") + " RETURNING id"
        cur = self.c.execute(s, tuple(params))
        if ret:
            row = cur.fetchone(); return _Res(cur, row["id"] if row else None)
        return _Res(cur)
    def commit(self): self.c.commit()
    def rollback(self): self.c.rollback()


