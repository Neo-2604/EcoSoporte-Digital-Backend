def _validate(kind, text):
    t = _clip(text, 400)
    if kind == "text":
        return (t, None) if t else (None, "Necesito una respuesta para continuar.")
    if kind == "number":
        n = _digits(t)
        return (n[:4], None) if n and int(n) > 0 else (None, "Escribe un número, por ejemplo 2.")
    if kind == "phone":
        n = _digits(t)
        return (n, None) if 7 <= len(n) <= 15 else (None, "Escribe un número de celular válido (7 a 15 dígitos).")
    if kind == "email_opt":
        if t.lower() in ("omitir", "no", "ninguno", ""):
            return "", None
        return (t, None) if re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", t) else (None, "Ese correo no parece válido. Escríbelo de nuevo o escribe «omitir».")
    return t, None


def _step(flow, i, data):
    """Siguiente pregunta del flujo o el consentimiento al terminar."""
    steps = FLOWS[flow]
    if i < len(steps):
        key, q, opts, _ = steps[i]
        return {"replies": [q], "options": opts or []}
    return {"replies": [CONSENT_TEXT], "options": [YES, "No, cancelar"]}


def _chat_reply(sess, text):
    state, data = sess["state"], json.loads(sess["data"] or "{}")
    text = _clip(text, 400)
    low = text.lower()
    if low in ("menú", "menu", "inicio", "cancelar", "volver") and state != "menu":
        return "menu", {}, _menu("Listo, volvemos al inicio.")
    if state == "menu":
        flow = {"Vender mis componentes": "venta", "Solicitar un servicio": "servicio", "Hablar con una persona": "persona"}.get(text)
        if not flow:
            if text == "Preguntas frecuentes" or "pregunta" in low or "ayuda" in low:
                return "faq", {}, {"replies": ["Estas son las dudas más comunes:"], "options": list(FAQ) + ["Volver al menú"]}
            if any(w in low for w in ("vender", "venta", "componente", "ram", "disco", "tarjeta")):
                flow = "venta"
            elif any(w in low for w in ("servicio", "soporte", "mantenimiento", "visita", "cotiz")):
                flow = "servicio"
            elif any(w in low for w in ("persona", "asesor", "humano", "llamar")):
                flow = "persona"
        if flow:
            intro = {"venta": "Perfecto, te ayudo a registrar tu solicitud de venta. Un asesor evaluará tus componentes y te contactará con una oferta.",
                     "servicio": "Con gusto. Registremos tu solicitud para que te contactemos.",
                     "persona": "Claro, dejemos tus datos y una persona del equipo te contactará."}[flow]
            data = {"flow": flow, "i": 0, "answers": {}}
            r = _step(flow, 0, data); r["replies"] = [intro] + r["replies"]
            return "flow", data, r
        return "menu", {}, _menu("No estoy seguro de haber entendido. Elige una opción:")
    if state == "faq":
        if text in FAQ:
            return "faq", {}, {"replies": [FAQ[text]], "options": list(FAQ) + ["Volver al menú"]}
        return "menu", {}, _menu()
    if state == "flow":
        flow, i = data["flow"], data["i"]
        steps = FLOWS[flow]
        if i < len(steps):
            key, q, opts, vk = steps[i]
            if opts:
                if text not in opts:
                    return "flow", data, {"replies": ["Por favor elige una de las opciones."], "options": opts}
                val = text
            else:
                val, err = _validate(vk, text)
                if err:
                    return "flow", data, {"replies": [err], "options": []}
            data["answers"][key] = val; data["i"] = i + 1
            return "flow", data, _step(flow, data["i"], data)
        # confirmación de consentimiento
        if text == YES:
            return "done", data, {"replies": [], "options": [], "save": True}
        return "menu", {}, _menu("Entendido, no guardé nada.")
    return "menu", {}, _menu()


