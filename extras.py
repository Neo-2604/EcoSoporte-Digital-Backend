def _expire_old(c):
    t = now()
    c.execute("UPDATE remote_sessions SET status='Expirada', ended_at=? WHERE status='Aprobada' AND approved_at<?",
              (t, _ago(REMOTE_APPROVAL_MINUTES * 60)))
    c.execute("UPDATE remote_sessions SET status='Expirada', ended_at=? WHERE status='Activa' AND started_at<?",
              (t, _ago(REMOTE_MAX_ACTIVE_HOURS * 3600)))
    c.commit()


def _event(c, sid, action, detail=None):
    c.execute("INSERT INTO remote_events(session_id,user_id,action,detail,created_at) VALUES(?,?,?,?,?)",
              (sid, g.user["id"], action, _clip(detail, 500) or None, now()))


SESSION_SQL = ("SELECT s.*, tk.created_at ticket_created, h.name host_name, h.address, h.port, h.ssh_user, h.os, h.fingerprint, co.name company, "
               "COALESCE(tech.name, s.technician_name, 'Cuenta eliminada') technician, ap.name approver FROM remote_sessions s JOIN remote_hosts h ON h.id=s.host_id "
               "LEFT JOIN companies co ON co.id=h.company_id LEFT JOIN users tech ON tech.id=s.technician_id "
               "LEFT JOIN users ap ON ap.id=s.approved_by LEFT JOIN tickets tk ON tk.id=s.ticket_id")


def _sessions(where="1=1", args=()):
    return [dict(r) for r in _db().execute(SESSION_SQL + f" WHERE {where} ORDER BY s.created_at DESC LIMIT 100", list(args)).fetchall()]


def _visible_where():
    u = g.user
    return ("1=1", []) if u["role"] in ("Administrador", "Soporte TI") else ("s.technician_id=?", [u["id"]])


def _connection_info(s):
    """Datos para que el técnico abra SSH desde SU equipo. El sistema nunca guarda claves ni contraseñas."""
    jump = os.environ.get("SSH_BASTION", "").strip()
    cmd = f"ssh {'-J ' + jump + ' ' if jump else ''}-p {s['port']} {s['ssh_user']}@{s['address']}"
    return {"command": cmd, "host": s["address"], "port": s["port"], "user": s["ssh_user"],
            "fingerprint": s["fingerprint"], "bastion": jump or None}


def _hosts_for(user):
    c = _db()
    if user["role"] in ("Administrador", "Soporte TI"):
        rows = c.execute("SELECT h.*, co.name company FROM remote_hosts h LEFT JOIN companies co ON co.id=h.company_id WHERE h.active ORDER BY h.name").fetchall()
    else:  # el técnico solo ve equipos de empresas con tickets asignados a él
        rows = c.execute("SELECT h.*, co.name company FROM remote_hosts h LEFT JOIN companies co ON co.id=h.company_id WHERE h.active AND h.company_id IN "
                         "(SELECT DISTINCT company_id FROM tickets WHERE assigned_to=? AND company_id IS NOT NULL AND status NOT IN ('Resuelto','Cerrado')) ORDER BY h.name",
                         (user["id"],)).fetchall()
    return [dict(r) for r in rows]


def _create_session(host_id, ticket_id, reason):
    c = _db(); u = g.user
    reason = _clip(reason, 500)
    if len(reason) < 10:
        return None, "Explica el motivo (mínimo 10 caracteres)."
    if host_id not in [h["id"] for h in _hosts_for(u)]:
        return None, "No tienes autorización sobre ese equipo."
    ticket_id = _int(ticket_id) or None
    if ticket_id:
        t = c.execute("SELECT id, assigned_to FROM tickets WHERE id=?", (ticket_id,)).fetchone()
        if not t or (u["role"] == "Técnico" and t["assigned_to"] != u["id"]):
            return None, "El ticket no existe o no está asignado a ti."
    elif u["role"] == "Técnico":
        return None, "Selecciona el ticket que justifica la sesión."
    t = now(); auto = u["role"] in ("Administrador", "Soporte TI")
    cur = c.execute("INSERT INTO remote_sessions(host_id,ticket_id,technician_id,reason,status,approved_by,approved_at,created_at) VALUES(?,?,?,?,?,?,?,?)",
                    (host_id, ticket_id, u["id"], reason, "Aprobada" if auto else "Solicitada", u["id"] if auto else None, t if auto else None, t))
    _event(c, cur.lastrowid, "Solicitud creada" + (" (aprobada automáticamente)" if auto else ""), reason)
    c.commit()
    return cur.lastrowid, None


def _notify_remote_client(c, s, title, body):
    """Avisa al cliente que creó el ticket de lo que pasa con el soporte remoto de su equipo."""
    if not s["ticket_id"]: return
    t = c.execute("SELECT created_by, created_at FROM tickets WHERE id=?", (s["ticket_id"],)).fetchone()
    if not t or not t["created_by"] or t["created_by"] == g.user["id"]: return
    year = str(t["created_at"] or "")[:4]
    code = f"TCK-{year if year.isdigit() else now()[:4]}-{int(s['ticket_id']):04d}"
    notify(c, "remoto", title.replace("{code}", code), body, actor_id=g.user["id"], actor_name=g.user["name"],
           target_user_id=t["created_by"], ticket_id=s["ticket_id"])


def _transition(sid, action, d):
    """Máquina de estados. Devuelve (mensaje_error | None)."""
    c = _db(); u = g.user
    s = c.execute("SELECT * FROM remote_sessions WHERE id=?", (sid,)).fetchone()
    if not s:
        return "Sesión no encontrada", 404
    coord = u["role"] in ("Administrador", "Soporte TI")
    if not coord and s["technician_id"] != u["id"]:
        return "Sesión no encontrada", 404
    st, t = s["status"], now()
    if action in ("approve", "reject"):
        if not coord: return "Solo Administrador o Soporte TI pueden decidir", 403
        if st != "Solicitada": return "La solicitud ya fue resuelta", 400
        if action == "approve":
            c.execute("UPDATE remote_sessions SET status='Aprobada', approved_by=?, approved_at=? WHERE id=?", (u["id"], t, sid))
            _event(c, sid, "Aprobada", f"Válida {REMOTE_APPROVAL_MINUTES} min para iniciar")
            _notify_remote_client(c, s, "Soporte remoto autorizado para tu ticket {code}",
                                  "El técnico se conectará a tu equipo en breve. Si no esperabas este soporte, avísanos.")
        else:
            c.execute("UPDATE remote_sessions SET status='Rechazada', approved_by=?, approved_at=?, ended_at=? WHERE id=?", (u["id"], t, t, sid))
            _event(c, sid, "Rechazada", d.get("note"))
    elif action == "start":
        if s["technician_id"] != u["id"]: return "Solo el técnico solicitante inicia la sesión", 403
        if st != "Aprobada": return "La sesión no está aprobada o ya expiró", 400
        c.execute("UPDATE remote_sessions SET status='Activa', started_at=? WHERE id=?", (t, sid))
        _event(c, sid, "Sesión iniciada", "El técnico abrió SSH desde su equipo")
        _notify_remote_client(c, s, "Soporte remoto en curso en tu ticket {code}", f"{u['name']} está atendiendo tu equipo de forma remota.")
    elif action in ("close", "escalate"):
        if st != "Activa": return "Solo se puede cerrar una sesión activa", 400
        summary = _clip(d.get("summary"), 1000)
        if len(summary) < 10: return "Describe qué hiciste (mínimo 10 caracteres)", 400
        if action == "close":
            c.execute("UPDATE remote_sessions SET status='Cerrada', ended_at=?, outcome='Resuelto', summary=? WHERE id=?", (t, summary, sid))
            _event(c, sid, "Sesión cerrada", summary)
            _notify_remote_client(c, s, "Terminó el soporte remoto de tu ticket {code}", summary[:160])
        else:
            c.execute("UPDATE remote_sessions SET status='Escalada', ended_at=?, outcome='Requiere visita presencial', summary=? WHERE id=?", (t, summary, sid))
            _event(c, sid, "Escalada a visita presencial", summary)
            _notify_remote_client(c, s, "Tu ticket {code} requiere visita presencial", summary[:160])
        if s["ticket_id"]:
            note = ("Soporte remoto finalizado: " if action == "close" else "Escalado a visita presencial tras soporte remoto: ") + summary
            c.execute("INSERT INTO ticket_updates(ticket_id,user_id,note,status) VALUES(?,?,?,?)", (s["ticket_id"], u["id"], note, "En espera" if action == "escalate" else None))
            if action == "escalate":
                c.execute("UPDATE tickets SET status='En espera', updated_at=CURRENT_TIMESTAMP WHERE id=?", (s["ticket_id"],))
    else:
        return "Acción no válida", 400
    c.commit()
    return None, 200


def _session_detail(sid):
    _expire_old(_db())
    w, a = _visible_where()
    rows = _sessions(f"s.id=? AND {w}", [sid] + a)
    if not rows: return None
    s = rows[0]
    s["events"] = [dict(r) for r in _db().execute(
        "SELECT e.action, e.detail, e.created_at, COALESCE(u.name, e.user_name, 'Cuenta eliminada') AS name FROM remote_events e LEFT JOIN users u ON u.id=e.user_id WHERE e.session_id=? ORDER BY e.id", (sid,)).fetchall()]
    s["connection"] = _connection_info(s) if s["status"] in ("Aprobada", "Activa") and s["technician_id"] == g.user["id"] else None
    return s


