def _validate_quote(f):
    err, d = [], {}
    d["name"] = f.get("name", "").strip()
    d["email"] = f.get("email", "").strip().lower()
    d["phone"] = re.sub(r"[\s\-()+]", "", f.get("phone", "")).strip()
    d["company"] = f.get("company", "").strip()
    d["city"] = f.get("city", "").strip()
    d["quantity"] = f.get("quantity", "").strip()
    d["message"] = f.get("message", "").strip()
    if not 2 <= len(d["name"]) <= 120: err.append("Escribe tu nombre (2 a 120 caracteres).")
    if not EMAIL_RE.match(d["email"]): err.append("Escribe un correo electrónico válido.")
    if d["phone"] and not re.fullmatch(r"\d{7,15}", d["phone"]): err.append("El celular debe tener entre 7 y 15 dígitos.")
    if len(d["company"]) > 120 or len(d["city"]) > 80 or len(d["quantity"]) > 40: err.append("Alguno de los campos es demasiado largo.")
    if not 10 <= len(d["message"]) <= 1500: err.append("Cuéntanos qué necesitas (10 a 1500 caracteres).")
    if f.get("consent") != "1": err.append("Debes autorizar el tratamiento de tus datos para recibir la cotización.")
    return d, err


@bp.post("/cotizar")
def quote_submit():
    u = _soft_user(); c = _db()
    if request.form.get("website"):  # campo trampa para bots
        return redirect(url_for("catalog.index"))
    iid = request.form.get("item_id", "")
    it = c.execute("SELECT * FROM catalog_items WHERE id=%s AND published", (int(iid),)).fetchone() if iid.isdigit() else None
    d, err = _validate_quote(request.form)
    if not err:
        recent = c.execute("SELECT COUNT(*) n FROM quote_requests WHERE lower(email)=%s AND created_at>%s",
                           (d["email"], (datetime.utcnow() - timedelta(hours=1)).strftime("%Y-%m-%d %H:%M:%S"))).fetchone()["n"]
        if recent >= 5: err.append("Recibimos varias solicitudes con este correo. Espera un momento e inténtalo de nuevo.")
    if err:
        for e in err: flash(e, "error")
        if it: return render_template("catalog_detail.html", it=it, price_label=price_label, is_admin=_is_admin(),
                                      benefits=[b.strip() for b in (it["benefits"] or "").splitlines() if b.strip()], form=request.form), 400
        return render_template("catalog_request.html", form=request.form), 400
    qid = c.execute("""INSERT INTO quote_requests(item_id,item_name,user_id,name,email,phone,company,city,quantity,message,consent,status,created_at,updated_at)
                       VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,TRUE,'Nueva',%s,%s) RETURNING id""",
                    (it["id"] if it else None, it["name"] if it else "Consulta general", u["id"] if u else None, d["name"], d["email"], d["phone"] or None,
                     d["company"] or None, d["city"] or None, d["quantity"] or None, d["message"], _now(), _now())).fetchone()["id"]
    c.execute("INSERT INTO quote_events(quote_id,user_name,status,note,public,created_at) VALUES(%s,%s,'Nueva','Solicitud recibida.',TRUE,%s)", (qid, d["name"], _now()))
    row = c.execute("SELECT * FROM quote_requests WHERE id=%s", (qid,)).fetchone()
    extras.notify(c, "cotizacion", f"Nueva solicitud de cotización {code(row)}", f"{d['name']} · {row['item_name']}", u["id"] if u else None, d["name"])
    c.commit()
    return redirect(url_for("catalog.quote_done", token=code(row), email=d["email"]))


