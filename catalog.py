@bp.route("/cotizaciones/<int:qid>", methods=["GET", "POST"])
@guard("Administrador", "Soporte TI")
def quote_detail(qid):
    c = _db()
    q = c.execute("SELECT * FROM quote_requests WHERE id=%s", (qid,)).fetchone()
    if not q: abort(404)
    if request.method == "POST":
        status = request.form.get("status", q["status"])
        note = request.form.get("note", "").strip()[:600]
        public = request.form.get("public") == "1"
        amount = None
        if request.form.get("quoted_amount", "").strip():
            try: amount = int(float(request.form["quoted_amount"].replace(".", "").replace(",", ".")))
            except ValueError: amount = -1
            if amount is not None and not 1 <= amount <= 1_000_000_000:
                flash("El valor cotizado debe ser un número positivo.", "error"); return redirect(url_for("catalog.quote_detail", qid=qid))
        if status not in QUOTE_STATUSES: abort(400)
        if status == "Cotización enviada" and not (amount or q["quoted_amount"]):
            flash("Para marcarla como «Cotización enviada» indica el valor cotizado.", "error"); return redirect(url_for("catalog.quote_detail", qid=qid))
        c.execute("UPDATE quote_requests SET status=%s,quoted_amount=COALESCE(%s,quoted_amount),assigned_to=%s,updated_at=%s WHERE id=%s",
                  (status, amount, g.user["id"], _now(), qid))
        if status != q["status"]:  # el cambio de estado siempre es visible; la nota solo si se marca como pública
            c.execute("INSERT INTO quote_events(quote_id,user_name,status,note,public,created_at) VALUES(%s,%s,%s,%s,TRUE,%s)",
                      (qid, g.user["name"], status, f"Estado: {status}", _now()))
        if note:
            c.execute("INSERT INTO quote_events(quote_id,user_name,status,note,public,created_at) VALUES(%s,%s,%s,%s,%s,%s)",
                      (qid, g.user["name"], status, note, public, _now()))
        if q["user_id"] and status != q["status"]:
            extras.notify(c, "cotizacion", f"Tu cotización {code(q)} ahora está: {status}", None, g.user["id"], g.user["name"], q["user_id"])
        c.commit(); flash("Solicitud actualizada.", "success")
        return redirect(url_for("catalog.quote_detail", qid=qid))
    events = c.execute("SELECT * FROM quote_events WHERE quote_id=%s ORDER BY id", (qid,)).fetchall()
    return render_template("catalog_quote.html", q=q, events=events, code=code, money=money, show_amount=True, staff_view=True, statuses=QUOTE_STATUSES)


