def guard(*roles):
    def deco(fn):
        @wraps(fn)
        def wrapper(*a, **k):
            return _roles(*roles)(fn)(*a, **k)
        return wrapper
    return deco


def _now():
    return datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")


def ensure_schema(c):
    pk = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    c.execute(f"""CREATE TABLE IF NOT EXISTS catalog_items(
      id {pk}, kind TEXT NOT NULL DEFAULT 'Servicio', category TEXT, name TEXT NOT NULL, summary TEXT, description TEXT,
      benefits TEXT, scope TEXT, price_mode TEXT NOT NULL DEFAULT 'Cotización', price INTEGER, price_unit TEXT,
      published BOOLEAN NOT NULL DEFAULT FALSE, sort_order INTEGER NOT NULL DEFAULT 100,
      created_by INTEGER, updated_by INTEGER, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)""")
    c.execute(f"""CREATE TABLE IF NOT EXISTS quote_requests(
      id {pk}, item_id INTEGER, item_name TEXT, user_id INTEGER, name TEXT NOT NULL, email TEXT NOT NULL, phone TEXT,
      company TEXT, city TEXT, quantity TEXT, message TEXT NOT NULL, consent BOOLEAN NOT NULL DEFAULT FALSE,
      status TEXT NOT NULL DEFAULT 'Nueva', assigned_to INTEGER, quoted_amount INTEGER, created_at TEXT NOT NULL, updated_at TEXT NOT NULL)""")
    c.execute(f"""CREATE TABLE IF NOT EXISTS quote_events(
      id {pk}, quote_id INTEGER NOT NULL REFERENCES quote_requests(id) ON DELETE CASCADE, user_name TEXT, status TEXT, note TEXT,
      public BOOLEAN NOT NULL DEFAULT FALSE, created_at TEXT NOT NULL)""")
    c.execute("CREATE INDEX IF NOT EXISTS idx_quote_requests_email ON quote_requests(lower(email))")
    c.execute("CREATE INDEX IF NOT EXISTS idx_quote_requests_user ON quote_requests(user_id)")
    if not c.execute("SELECT 1 FROM catalog_items LIMIT 1").fetchone():
        for i, (name, cat, summ, scope) in enumerate(DRAFTS):
            c.execute("""INSERT INTO catalog_items(kind,category,name,summary,scope,price_mode,published,sort_order,created_at,updated_at)
                         VALUES('Servicio',%s,%s,%s,%s,'Cotización',FALSE,%s,%s,%s)""", (cat, name, summ, scope, (i + 1) * 10, _now(), _now()))


def item_code(item_id):
    """Código visible y estable del producto/servicio (CAT-0001): sirve para buscarlo."""
    return f"CAT-{int(item_id):04d}"


CODE_RE = re.compile(r"^(?:cat-?|#)\s*0*(\d{1,9})$", re.I)


def _search_clause(q, args, cols=("name", "summary", "description")):
    """Busca por código (CAT-0001, cat1, #1) o por texto."""
    m = CODE_RE.match(q.strip())
    if m:
        args.append(int(m.group(1))); return "id=%s"
    args += [f"%{q}%"] * len(cols)
    return "(" + " OR ".join(f"{c} ILIKE %s" for c in cols) + ")"


def code(q):
    return f"COT-{q['created_at'][:4]}-{q['id']:04d}"


def _soft_user():
    """En páginas públicas: si hay sesión, usa el diseño de la plataforma con la persona identificada."""
    if g.get("user") is None and session.get("user_id"):
        u = _db().execute("SELECT * FROM users WHERE id=%s AND active", (session["user_id"],)).fetchone()
        if u: g.user = u
    return g.get("user")


def money(v):
    return "$" + f"{int(v):,}".replace(",", ".")


def price_label(it):
    if it["price_mode"] == "Cotización" or not it["price"]:
        return "Requiere cotización"
    base = money(it["price"]) + (f" {it['price_unit']}" if it["price_unit"] else "")
    return ("Desde " + base) if it["price_mode"] == "Desde" else base


def _is_admin():
    u = g.get("user"); return bool(u and u["role"] == "Administrador")


def _is_staff():
    u = g.get("user"); return bool(u and u["role"] in ("Administrador", "Soporte TI"))


