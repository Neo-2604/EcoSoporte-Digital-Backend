@bp.route("/admin/nuevo", methods=["GET", "POST"])
@bp.route("/admin/<int:iid>", methods=["GET", "POST"])
@guard("Administrador")
def admin_edit(iid=None):
    c = _db()
    it = c.execute("SELECT * FROM catalog_items WHERE id=%s", (iid,)).fetchone() if iid else None
    if iid and not it: abort(404)
    if request.method == "GET": return _item_form(it)
    f = request.form
    d = dict(kind=f.get("kind"), category=f.get("category", "").strip()[:60] or None, name=f.get("name", "").strip(), summary=f.get("summary", "").strip(),
             description=f.get("description", "").strip(), benefits=f.get("benefits", "").strip(), scope=f.get("scope", "").strip(),
             price_mode=f.get("price_mode"), price_unit=f.get("price_unit", "").strip()[:30] or None)
    err = []
    if d["kind"] not in KINDS: err.append("Tipo no válido.")
    if d["price_mode"] not in PRICE_MODES: err.append("Modalidad de precio no válida.")
    if not 3 <= len(d["name"]) <= 120: err.append("El nombre debe tener entre 3 y 120 caracteres.")
    if len(d["summary"]) > 220 or len(d["description"]) > 3000 or len(d["benefits"]) > 1500 or len(d["scope"]) > 1500: err.append("Alguno de los textos es demasiado largo.")
    price = None
    if d["price_mode"] in ("Precio fijo", "Desde"):
        try: price = int(float(f.get("price", "").replace(".", "").replace(",", ".")))
        except ValueError: price = None
        if not price or not 1 <= price <= 1_000_000_000: err.append("Indica un precio en COP mayor que cero o cambia a «Cotización».")
    try: order = int(f.get("sort_order", "100"))
    except ValueError: order = 100
    if err:
        for e in err: flash(e, "error")
        return _item_form({**d, "id": iid, "price": f.get("price"), "sort_order": order}), 400
    published = f.get("published") == "1"
    if it:
        c.execute("""UPDATE catalog_items SET kind=%s,category=%s,name=%s,summary=%s,description=%s,benefits=%s,scope=%s,price_mode=%s,price=%s,
                     price_unit=%s,published=%s,sort_order=%s,updated_by=%s,updated_at=%s WHERE id=%s""",
                  (d["kind"], d["category"], d["name"], d["summary"], d["description"], d["benefits"], d["scope"], d["price_mode"], price, d["price_unit"],
                   published, order, g.user["id"], _now(), iid))
    else:
        c.execute("""INSERT INTO catalog_items(kind,category,name,summary,description,benefits,scope,price_mode,price,price_unit,published,sort_order,
                     created_by,updated_by,created_at,updated_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                  (d["kind"], d["category"], d["name"], d["summary"], d["description"], d["benefits"], d["scope"], d["price_mode"], price, d["price_unit"],
                   published, order, g.user["id"], g.user["id"], _now(), _now()))
    c.commit(); flash("Catálogo actualizado.", "success")
    return redirect(url_for("catalog.admin"))


